class TestComovingDistance(unittest.TestCase):
    def setUp(self):
        self.cosmo = Cosmology(
            Omegab=0.055,
            Omegam=0.35140742,
            H0=63.6,
            w0=-0.42,
            wa=-1.75,
            mnu=0.06,
        )

    def tearDown(self):
        self.cosmo = None

    def test_reference_distance(self):
        np.testing.assert_allclose(
            self.cosmo.comoving_distance(Z_REF), CHI_REF, rtol=1e-9, atol=1e-8
        )

    def test_neutrino_matter_like(self):
        np.testing.assert_allclose(
            self.cosmo.comoving_distance(Z_REF, neutrino_matter_like=True),
            CHI_NML_REF,
            rtol=1e-9,
            atol=1e-8,
        )

    def test_distance_to_lss(self):
        np.testing.assert_allclose(self.cosmo.comoving_distance(1100.0), [CHI_STAR_REF], rtol=1e-9)

    def test_zero_redshift_is_exact(self):
        self.assertEqual(float(self.cosmo.comoving_distance(0.0)[0]), 0.0)

    def test_scalar_input_keeps_length_one_axis(self):
        self.assertEqual(self.cosmo.comoving_distance(1.0).shape, (1,))

    def test_cache_invalidates_when_parameters_change(self):
        first = self.cosmo.comoving_distance(1.0).copy()
        self.cosmo.w0 = -1.0
        second = self.cosmo.comoving_distance(1.0)
        self.assertFalse(np.allclose(first, second))


class TestSpectralEquivalenceDE(unittest.TestCase):
    def test_wcdm_newton(self):
        got = spectral_equivalence_de(THETA_REF, Z_REF, wcdm=True)
        self.assertEqual(got.shape, (1, Z_REF.size))
        np.testing.assert_allclose(got[0], W_CONST_REF, rtol=1e-8, atol=1e-10)

    def test_wcdm_finite_diff_newton(self):
        got = spectral_equivalence_de(THETA_REF, Z_REF, wcdm=True, method="finite_diff_newton")
        np.testing.assert_allclose(got[0], W_CONST_FD_REF, rtol=1e-6, atol=1e-9)

    def test_wcdm_neutrino_matter_like(self):
        got = spectral_equivalence_de(THETA_REF, Z_REF, wcdm=True, neutrino_matter_like=True)
        np.testing.assert_allclose(got[0], W_CONST_NML_REF, rtol=1e-8, atol=1e-10)

    def test_w0wa(self):
        w0, wa, err = spectral_equivalence_de(THETA_REF, Z_REF, return_error=True)
        self.assertEqual(w0.shape, (1, Z_REF.size))
        # Underdetermined valley: compare the physical residual tightly and
        # the parameters loosely.
        np.testing.assert_allclose(w0[0], W0_REF, atol=1e-5)
        np.testing.assert_allclose(wa[0], WA_REF, atol=1e-5)
        np.testing.assert_allclose(err[0], ERR_W0WA_REF, atol=1e-8)

    def test_w0wa_neutrino_matter_like(self):
        w0, wa = spectral_equivalence_de(THETA_REF, Z_REF, neutrino_matter_like=True)
        np.testing.assert_allclose(w0[0], W0_NML_REF, atol=1e-5)
        np.testing.assert_allclose(wa[0], WA_NML_REF, atol=1e-5)

    def test_wcdm_mnu_zero(self):
        got = spectral_equivalence_de(THETA_C3, Z_C3, wcdm=True)
        np.testing.assert_allclose(got[0], W_CONST_C3, rtol=1e-8, atol=1e-10)

    def test_wcdm_outside_emulator_box_is_unaffected(self):
        got = spectral_equivalence_de(THETA_C4, Z_C4, wcdm=True)
        np.testing.assert_allclose(got[0], W_CONST_C4, rtol=1e-8, atol=1e-10)

    def test_return_error(self):
        result = spectral_equivalence_de(THETA_REF, Z_REF, wcdm=True, return_error=True)
        self.assertEqual(len(result), 2)
        self.assertEqual(result[0].shape, (1, Z_REF.size))
        self.assertEqual(result[1].shape, (1, Z_REF.size))

    def test_batch_matches_single(self):
        z = np.array([0.2, 0.7, 1.5])
        batch_theta = np.vstack([THETA_C3, THETA_C5])
        w0_batch, wa_batch = spectral_equivalence_de(batch_theta, z)
        for index, row in enumerate(batch_theta):
            w0_single, wa_single = spectral_equivalence_de(row, z)
            np.testing.assert_array_equal(w0_batch[index], w0_single[0])
            np.testing.assert_array_equal(wa_batch[index], wa_single[0])

    def test_invalid_method(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_de(THETA_REF, Z_REF, wcdm=True, method="brentq")

    def test_invalid_theta_shape(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_de(THETA_REF[:-1], Z_REF)

    def test_invalid_redshift(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_de(THETA_REF, [0.0, -1.0])

    def test_integer_redshifts(self):
        got = spectral_equivalence_de(THETA_REF, [0, 1, 2, 3], wcdm=True)
        self.assertEqual(got.dtype, np.float64)


class TestSpectralEquivalenceAS(unittest.TestCase):
    @unittest.skipUnless(HAS_AS_DATA, f"{BUNDLE_NAME} or {RATIO_BUNDLE_NAME} is not present")
    def test_emulator_backend(self):
        got = spectral_equivalence_as(THETA_C5, Z_C5, W_CONST_C5, sigma8_type="emulator")
        self.assertEqual(got.shape, (1, Z_C5.size))
        np.testing.assert_allclose(got[0], AS_EMULATOR_WCDM_C5, rtol=1e-6)

    @unittest.skipUnless(
        HAS_AS_DATA and HAS_CLASSY, f"{BUNDLE_NAME}, {RATIO_BUNDLE_NAME} or classy is not present"
    )
    def test_class_backend(self):
        got = spectral_equivalence_as(THETA_REF, Z_REF, W0_REF, WA_REF, sigma8_type="class")
        np.testing.assert_allclose(got[0], AS_CLASS_REF, rtol=CLASS_AS_RTOL)

    @unittest.skipUnless(
        HAS_AS_DATA and HAS_CAMB, f"{BUNDLE_NAME}, {RATIO_BUNDLE_NAME} or camb is not present"
    )
    def test_camb_backend(self):
        got = spectral_equivalence_as(THETA_REF, Z_REF, W0_REF, WA_REF, sigma8_type="camb")
        np.testing.assert_allclose(got[0], AS_CAMB_REF, rtol=CAMB_AS_RTOL)

    @unittest.skipUnless(
        HAS_AS_DATA and HAS_CLASSY, f"{BUNDLE_NAME}, {RATIO_BUNDLE_NAME} or classy is not present"
    )
    def test_wcdm_class_backend(self):
        got = spectral_equivalence_as(THETA_REF, Z_REF, W_CONST_REF, sigma8_type="class")
        np.testing.assert_allclose(got[0], AS_CLASS_WCDM_REF, rtol=CLASS_AS_RTOL)

    @unittest.skipUnless(
        HAS_AS_DATA and HAS_CAMB, f"{BUNDLE_NAME}, {RATIO_BUNDLE_NAME} or camb is not present"
    )
    def test_wcdm_camb_backend(self):
        got = spectral_equivalence_as(THETA_REF, Z_REF, W_CONST_REF, sigma8_type="camb")
        np.testing.assert_allclose(got[0], AS_CAMB_WCDM_REF, rtol=CAMB_AS_RTOL)

    @unittest.skipUnless(HAS_DATA and HAS_CLASSY, f"{BUNDLE_NAME} or classy is not present")
    def test_out_of_bounds_falls_back_to_camb(self):
        # w = -1.4 is outside the emulator box, so the auxiliary sigma8 comes
        # from CAMB even when the target backend is CLASS.
        got = spectral_equivalence_as(
            THETA_C4, Z_C4, W_CONST_C4, sigma8_type="class", fallback_to_camb=True
        )
        np.testing.assert_allclose(got[0], AS_CLASS_WCDM_C4, rtol=CLASS_AS_RTOL)

    @unittest.skipUnless(HAS_DATA and HAS_CAMB, f"{BUNDLE_NAME} or camb is not present")
    def test_out_of_bounds_camb(self):
        got = spectral_equivalence_as(
            THETA_C4, Z_C4, W_CONST_C4, sigma8_type="camb", fallback_to_camb=True
        )
        np.testing.assert_allclose(got[0], AS_CAMB_WCDM_C4, rtol=CAMB_AS_RTOL)

    @unittest.skipUnless(HAS_DATA and HAS_CAMB, f"{BUNDLE_NAME} or camb is not present")
    def test_auxiliary_out_of_bounds_requires_fallback(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_as(THETA_C4, Z_C4, W_CONST_C4, sigma8_type="camb")

    @unittest.skipUnless(HAS_AS_DATA, f"{BUNDLE_NAME} or {RATIO_BUNDLE_NAME} is not present")
    def test_emulator_backend_rejects_out_of_bounds(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_as(THETA_C4, Z_C4, W_CONST_C4, sigma8_type="emulator")

    @unittest.skipUnless(HAS_AS_DATA, f"{BUNDLE_NAME} or {RATIO_BUNDLE_NAME} is not present")
    def test_wa_defaults_to_zero(self):
        got = spectral_equivalence_as(THETA_C5, Z_C5, W_CONST_C5, sigma8_type="emulator")
        explicit = spectral_equivalence_as(
            THETA_C5, Z_C5, W_CONST_C5, np.zeros(Z_C5.size), sigma8_type="emulator"
        )
        np.testing.assert_array_equal(got, explicit)

    @unittest.skipUnless(HAS_AS_DATA, f"{BUNDLE_NAME} or {RATIO_BUNDLE_NAME} is not present")
    def test_batch_matches_single(self):
        z = np.array([0.3, 1.0, 2.0])
        batch_theta = np.vstack([THETA_C3, THETA_C5])
        w0 = np.array([[-0.9, -0.9, -0.9], [-1.03, -1.02, -1.01]])
        wa = np.array([[0.3, 0.3, 0.3], [0.1, 0.1, 0.1]])
        batch = spectral_equivalence_as(batch_theta, z, w0, wa, sigma8_type="emulator")
        for index, row in enumerate(batch_theta):
            single = spectral_equivalence_as(row, z, w0[index], wa[index], sigma8_type="emulator")
            # BLAS may reassociate a batched matrix product differently from a
            # single-row product, so allow a few ulps.
            np.testing.assert_allclose(batch[index], single[0], rtol=1e-9, atol=0.0)

    def test_invalid_sigma8_type(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_as(THETA_REF, Z_REF, W0_REF, sigma8_type="boltzmann")

    def test_invalid_w0_shape(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_as(THETA_REF, Z_REF, [1.0, 2.0])

    def test_theta_must_be_two_dimensional_or_flat(self):
        with self.assertRaises(ValueError):
            spectral_equivalence_as(np.ones((1, 2, 8)), Z_REF, W0_REF)


if __name__ == "__main__":
    unittest.main()
