"""Tests for the cosmological spectral-equivalence module.

The golden values below were generated by running the reference
``CEmulator/SpectralEquivalence.py`` in the environment csstemu was validated
in (Python 3.9.19, numpy 1.26.4, scipy 1.13.1, classy 3.2.1, camb 1.5.8).

Two reference behaviours make exact parameter-by-parameter agreement
impossible or meaningless:

* The ``w0waCDM`` problem is underdetermined. One distance constraint with two
  parameters leaves a one-dimensional solution curve, so the returned point
  depends on the optimiser path. The tests therefore use a looser tolerance
  for ``w0``/``wa`` and check ``err_chi`` tightly.
* CLASS's ``sigma8`` changes at the ``1e-4`` level between major versions. The
  class-backend tolerance is widened when the installed classy is not the
  reference version; the camb backend is stable to better than ``1e-6``.

The emulator backend is a jet extension; its golden values were generated by
evaluating the reference emulator for both the target and the auxiliary model.
"""

